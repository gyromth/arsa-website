// Build-time generator: simplify Natural Earth land rings and emit TS data
// used by the interactive hero globe at runtime (projection is done in JS).
import { readFileSync, writeFileSync } from 'node:fs';
import * as topojson from 'topojson-client';

const STEP_MIN = 0.45; // min spacing (deg, cos-scaled) between kept points

const land = topojson.feature(
  JSON.parse(readFileSync('scripts/land-110m.json', 'utf8')),
  'land',
);
const multi = land.features
  ? land.features.flatMap((f) => (f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : [f.geometry.coordinates]))
  : land.coordinates;

// Each ring flattened as [lon, lat, ...]; rings may span the whole hemisphere.
const flat = [];
const splits = [];

for (const poly of multi) {
  const outer = poly[0];
  const pts = [];
  let last = null;
  for (const [lon, lat] of outer) {
    if (last) {
      const dl = (lon - last[0]) * Math.cos((lat * Math.PI) / 180);
      const dp = lat - last[1];
      if (Math.hypot(dl, dp) < STEP_MIN) continue;
    }
    last = [lon, lat];
    pts.push(Math.round(lon * 50) / 50, Math.round(lat * 50) / 50);
  }
  if (pts.length > 6) {
    splits.push(pts.length / 2);
    flat.push(...pts);
  }
}

const cities = [
  ['delhi', 77.2, 28.6],
  ['moscow', 37.6, 55.75],
  ['bangkok', 100.5, 13.75],
  ['frankfurt', 8.68, 50.1],
  ['singapore', 103.8, 1.35],
  ['london', -0.1, 51.5],
];
const routes = [
  ['delhi', 'moscow'],
  ['delhi', 'bangkok'],
  ['london', 'bangkok'],
  ['delhi', 'frankfurt'],
  ['delhi', 'singapore'],
  ['london', 'frankfurt'],
];
const cityIdx = {};
cities.forEach(([name], i) => (cityIdx[name] = i));
const routePairs = routes.map(([a, b]) => [cityIdx[a], cityIdx[b]]);

const out = `// AUTO-GENERATED by scripts/build-globe-data.mjs (Natural Earth 110m land).
// Simplified coastline rings + route poles for the interactive hero globe.
export const LAND_RING_FLAT: readonly number[] = ${JSON.stringify(flat)};
export const LAND_RING_SPLITS: readonly number[] = ${JSON.stringify(splits)};
export const CITY_POLES: readonly [number, number][] = ${JSON.stringify(cities.map(([, lon, lat]) => [lon, lat]))};
export const ROUTE_PAIRS: readonly [number, number][] = ${JSON.stringify(routePairs)};
`;
writeFileSync('src/globe-data.ts', out);
const points = splits.reduce((a, b) => a + b, 0);
console.log(`rings=${splits.length} points=${points}`);
